#!/usr/bin/env bash
# Our pinned Slint: upstream tag + patch queue (card #52, docs/components/c4-toolkit/).
#   slint-fork.sh setup            clone the pinned commit into third_party/slint/src, apply the queue
#   slint-fork.sh config           write third_party/slint/patch.toml ([patch.crates-io] for the checkout)
#   slint-fork.sh export           rewrite third_party/slint/patches from the commits in the checkout
#   slint-fork.sh rebase <ref>     dry run: apply the queue onto <ref> in a scratch clone, report conflicts
# Use the result with: cargo --config <repo>/third_party/slint/patch.toml build
set -euo pipefail

root=$(cd "$(dirname "$0")/../.." && pwd)
fork=$root/third_party/slint
src=$fork/src
# shellcheck source=/dev/null
. "$fork/UPSTREAM"

# Fixed identity and dates so a queue applies to the same commits on every machine.
export GIT_AUTHOR_NAME=Atos GIT_AUTHOR_EMAIL=atos@localhost GIT_COMMITTER_NAME=Atos GIT_COMMITTER_EMAIL=atos@localhost

queue() { find "$fork/patches" -name '*.patch' | sort; }

checkout() { # <dir> <ref> : shallow-fetch one ref, never trust a moving name for the pin
  rm -rf "$1" && git init -q "$1"
  git -C "$1" fetch -q --depth 1 "$repo" "$2"
  git -C "$1" checkout -q FETCH_HEAD
}

apply_queue() { # <dir> [git am flags]
  local dir=$1; shift
  local p
  for p in $(queue); do git -C "$dir" am -q "$@" "$p" || { echo "FAILED: $(basename "$p")" >&2; return 1; }; done
}

case "${1:-}" in
setup)
  checkout "$src" "$commit"
  [ "$(git -C "$src" rev-parse HEAD)" = "$commit" ] || { echo "pin mismatch: $tag is not $commit" >&2; exit 1; }
  git -C "$src" tag base
  apply_queue "$src"
  "$0" config
  ;;
config)
  # One entry per publishable crate in Slint's workspace; unused ones only cause a cargo warning.
  cargo metadata --no-deps --format-version 1 --manifest-path "$src/Cargo.toml" |
    python3 -I -c '
import json, sys, os
print("# Generated by tools/slint-fork/slint-fork.sh config. Do not edit.\n[patch.crates-io]")
for p in sorted(json.load(sys.stdin)["packages"], key=lambda p: p["name"]):
    if p["publish"] != []:
        print("%s = { path = \"%s\" }" % (p["name"], os.path.dirname(p["manifest_path"])))
' >"$fork/patch.toml"
  echo "wrote $fork/patch.toml"
  ;;
export)
  rm -f "$fork"/patches/*.patch
  git -C "$src" format-patch -q --no-signature --zero-commit -N -o "$fork/patches" base..HEAD
  ls "$fork/patches"
  ;;
rebase)
  ref=${2:?usage: rebase <ref (tag, branch or sha)>}
  tmp=$(mktemp -d)
  trap 'rm -rf "$tmp"' EXIT
  checkout "$tmp/s" "$ref"
  # --3way needs the blobs the patches were made against: fetch the pinned commit too.
  git -C "$tmp/s" fetch -q --depth 1 "$repo" "$commit"
  echo "onto $(git -C "$tmp/s" rev-parse --short HEAD) ($ref); $(queue | wc -l | tr -d ' ') patches"
  # 3-way: a patch whose context moved still applies; only real overlaps stop it.
  apply_queue "$tmp/s" --3way && echo "all patches apply" || { git -C "$tmp/s" status --short | head -20; exit 1; }
  ;;
*) sed -n '2,7p' "$0"; exit 2 ;;
esac
